/** Un catalogue traduit : mêmes clés que l'anglais, toutes facultatives (ce qui
 *  manque retombe sur l'anglais), mais aucune clé inventée ne passe. */
type Deep<T> = { [K in keyof T]?: T[K] extends string ? string : Deep<T[K]> }
export type Catalog = Deep<typeof en>

export default en
